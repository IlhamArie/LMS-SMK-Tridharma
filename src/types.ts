export type UserRole = 'operator' | 'guru' | 'siswa';

export interface SystemConfig {
  institutionName: string;
  kkm: number;
  masterAccessCode: string;
  description: string;
  bannerText: string;
  logoUrl?: string;
}

export interface Announcement {
  id: string;
  title: string;
  content: string;
  category: 'Penting' | 'Akademik' | 'Kegiatan' | 'Ujian' | 'Umum';
  date: string; // YYYY-MM-DD
  author: string; // e.g. "Operator Sekolah", "Waka Kurikulum", etc.
  isPinned?: boolean;
  isActive: boolean;
}

export interface ClassRoom {
  id: string;
  name: string; // e.g. "X RPL 1", "XI TKJ 1"
  gradeLevel: string; // "X", "XI", "XII"
  major: string; // "Rekayasa Perangkat Lunak", etc.
}

export interface Subject {
  id: string;
  code: string;
  name: string; // e.g. "Matematika Terapan", "Pemrograman Web"
  category: 'Kejuruan' | 'Umum' | 'Muatan Lokal';
}

export interface Teacher {
  id: string;
  nip: string;
  name: string;
  subjectIds: string[]; // IDs of subjects taught
  accessCode: string; // Password generated by operator
}

export interface Student {
  id: string;
  nis: string;
  name: string;
  classId: string;
}

export type AttendanceStatus = 'Hadir' | 'Izin' | 'Sakit' | 'Alfa';

export interface AttendanceRecord {
  id: string;
  date: string; // YYYY-MM-DD
  classId: string;
  subjectId: string;
  teacherId: string;
  studentId: string;
  status: AttendanceStatus;
  notes?: string;
}

export interface Material {
  id: string;
  title: string;
  meetingNo: number;
  classId: string;
  subjectId: string;
  teacherId: string;
  url: string;
  description: string; // supports LaTeX/MathJax formulas e.g. \(f(x) = x^2\)
  createdAt: string;
}

export interface Assignment {
  id: string;
  title: string;
  meetingNo: number;
  classId: string;
  subjectId: string;
  teacherId: string;
  deadline: string; // YYYY-MM-DDTHH:mm
  description: string; // supports LaTeX formulas
  createdAt: string;
}

export interface Submission {
  id: string;
  assignmentId: string;
  studentId: string;
  submissionUrl: string;
  submittedAt: string;
  status: 'Sudah dikumpulkan' | 'Terlambat';
  grade?: number;
  feedback?: string;
}

export interface SummativeGrade {
  id: string;
  studentId: string;
  classId: string;
  subjectId: string;
  teacherId: string;
  evaluationNumber: number; // 1 to 10 (Sumatif 1 - 10)
  chapterTitle: string; // Bab / Pokok Bahasan
  score: number; // 0 - 100
  updatedAt: string;
}

export interface UserSession {
  role: UserRole;
  name: string;
  identifier: string; // operator ID, teacher ID, or student NIS/ID
  classId?: string; // for student
  teacherData?: Teacher;
  studentData?: Student;
}
